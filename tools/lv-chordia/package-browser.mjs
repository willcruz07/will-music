// Rebuild redistributable static files from the pinned, validated export and CQT plans.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { zipSync } from 'fflate';

const root = fileURLToPath(new URL('../../', import.meta.url));
const source = join(root, 'tools/lv-chordia/.cache/browser');
const manifest = JSON.parse(readFileSync(join(source, 'manifest.json'), 'utf8'));
const dest = join(root, 'apps/web/public/models/lv-chordia-v1');
mkdirSync(dest, { recursive: true });
writeFileSync(join(dest, 'NOTICE.txt'), readFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), 'utf8').split('## Musetric')[0]);
const registry = {};
const readVerified = (directory, asset) => {
  const data = readFileSync(join(directory, asset.file));
  if (data.length !== asset.bytes || createHash('sha256').update(data).digest('hex') !== asset.sha256) throw new Error(`Invalid source asset: ${asset.file}`);
  return data;
};
const add = (id, file, data) => {
  writeFileSync(join(dest, file), data);
  registry[id] = { url: `/models/lv-chordia-v1/${file}`, file, bytes: data.length, sha256: createHash('sha256').update(data).digest('hex') };
};
manifest.models.forEach((asset, index) => add(`lv${index}`, asset.file, readVerified(join(root, 'tools/lv-chordia/.cache/export-centered'), asset)));
add('lvDictionary', 'dictionary.json', readVerified(source, manifest.dictionary));
// ZIP allows inflating only the tuning plan in use, rather than parsing all 100 plans in memory.
const files = Object.fromEntries(manifest.plans.map((asset) => [asset.file, [readVerified(source, asset), { mtime: new Date('2020-01-01T00:00:00Z') }]]));
add('lvPlans', 'plans.zip', zipSync(files, { level: 9 }));
writeFileSync(join(root, 'packages/engine/src/lvModels.ts'), '// Generated by tools/lv-chordia/package-browser.mjs. Pinned browser assets.\nexport const LV_MODELS = ' + JSON.stringify(registry, null, 2) + ' as const;\n');
console.log(`Packaged ${Object.values(registry).reduce((sum, asset) => sum + asset.bytes, 0)} bytes of LV-Chordia assets.`);
